import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {app,server} from '../src/server.js';
import {offlineInventoryServer} from './helpers/offline-inventory-server.js';

globalThis.fetch=()=>{throw Error('Live network forbidden');};
test('server import opens no listener and every route/method is unique',()=>{
  assert.equal(server,null);
  const layers=(app._router||app.router).stack.filter(layer=>layer.route);
  const identities=layers.flatMap(({route})=>Object.keys(route.methods).filter(method=>route.methods[method]).map(method=>`${method} ${route.path}`));
  assert.equal(new Set(identities).size,identities.length,'Duplicate route handlers must be resolved, even when git merge reports no conflicts');
  assert.equal(identities.filter(id=>id==='get /api/scan-request').length,1);
  assert.equal(identities.filter(id=>id==='post /api/scan-request').length,1);
});
test('server-only HTTP middleware preserves six legacy rows and request timestamp during versioned publication',async t=>{
  const previous=process.env.NORTH_STAR_UPLOAD_KEY;
  process.env.NORTH_STAR_UPLOAD_KEY='server-release-fixture';
  t.after(()=>{if(previous===undefined)delete process.env.NORTH_STAR_UPLOAD_KEY;else process.env.NORTH_STAR_UPLOAD_KEY=previous;});
  const fixture=await offlineInventoryServer(t);
  const six=Array.from({length:6},(_,i)=>({id:`legacy-ebay-${i}`,source:'eBay',capturedAt:'2026-11-10T22:00:49.498Z',url:`https://synthetic.invalid/${i}`,custom:{keep:true}}));
  fs.writeFileSync(fixture.file,JSON.stringify(six));
  const requestFile=path.join(path.dirname(fixture.file),'scan-request.json');
  fs.writeFileSync(requestFile,JSON.stringify({requestedAt:'2026-11-10T22:00:49.498Z'}));
  const requestBefore=fs.readFileSync(requestFile);
  const inventoryBefore=fs.readFileSync(fixture.file);
  const headers={Authorization:'Bearer server-release-fixture'};
  const base='https://synthetic.invalid/api/opportunities';
  const row={id:'new-facebook',title:'Synthetic review fixture',source:'Moda',url:'',price:null,marketValue:null,projectedProfit:null,score:0,decision:'REVIEW',image:null};
  const baseline=await (await fixture.fetchImpl(base+'/inventory',{headers})).json();
  assert.equal(baseline.complete,true);assert.deepEqual(baseline.opportunities,six);
  assert.match(baseline.version,/^"[a-f0-9]{64}"$/);
  const blind=await fixture.parsedRequest(JSON.stringify([...six,row]),{authorization:headers.Authorization});
  assert.equal(blind.status,428);assert.deepEqual(fs.readFileSync(fixture.file),inventoryBefore);
  const changed=structuredClone(six);changed[0].capturedAt='2026-11-13T00:00:00.000Z';
  const rewrite=await fixture.parsedRequest(JSON.stringify([...changed,row]),{authorization:headers.Authorization,'if-match':baseline.version});
  assert.equal(rewrite.status,409);assert.deepEqual(fs.readFileSync(fixture.file),inventoryBefore);
  const accepted=await fixture.parsedRequest(JSON.stringify([...six,row]),{authorization:headers.Authorization,'if-match':baseline.version});
  assert.equal(accepted.status,200);
  const saved=JSON.parse(fs.readFileSync(fixture.file));
  assert.deepEqual(saved.slice(0,6),six);assert.deepEqual(saved[6],row);
  const stale=await fixture.parsedRequest(JSON.stringify([...six,row,{...row,id:'stale'}]),{authorization:headers.Authorization,'if-match':baseline.version});
  assert.equal(stale.status,412);assert.deepEqual(JSON.parse(fs.readFileSync(fixture.file)),saved);
  const publicRows=await (await fixture.fetchImpl(base)).json();
  assert.deepEqual(publicRows,[row]);
  const requested=await (await fixture.fetchImpl('https://synthetic.invalid/api/scan-request',{headers})).json();
  assert.equal(requested.requestedAt,'2026-11-10T22:00:49.498Z');
  assert.deepEqual(fs.readFileSync(requestFile),requestBefore);
});
